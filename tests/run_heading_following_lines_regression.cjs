const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../2-导入_InDesign/journal_layout_rules.jsxinc'),'utf8'),ctx);
const frame={id:1,parentPage:{id:10},geometricBounds:[0,0,100,180],textFramePreferences:{textColumnCount:2}};
const nextFrame={...frame,id:2};
const nextPageFrame={...frame,id:3,parentPage:{id:11}};
const line=(horizontalOffset,owner=frame)=>({contents:'文字',horizontalOffset,insertionPoints:[{parentTextFrames:[owner]}]});
const p=(...lines)=>({isValid:true,lines});
const count=ctx.JournalLayout.headingFollowingLineCount;
const heading=p(line(10));
assert.equal(count(heading,p(line(10),line(100))),1);
assert.equal(count(heading,p(line(100),line(100))),0);
assert.equal(count(heading,p(line(10),line(10,nextFrame))),1);
assert.equal(count(heading,p(line(10),line(10))),2);
const issue=ctx.JournalLayout.headingFollowingIssue;
assert.equal(issue(heading,p(line(10,nextFrame)),false),'HEADING_ORPHAN');
assert.equal(issue(heading,p(line(10)),false),null);
assert.equal(issue(heading,p(line(10),line(100)),false),null);
assert.equal(issue(heading,p(line(10),line(10,nextPageFrame)),false),null);
assert.equal(issue(heading,p(line(100)),false),'HEADING_ORPHAN');
assert.equal(issue(heading,p(line(100)),true),null);
assert.equal(issue(heading,p(line(10,nextPageFrame)),true),'HEADING_ORPHAN');
const repair=ctx.JournalLayout.repairPrimaryHeadingPageBreaks;
const primary=Object.assign(p(line(10)),{appliedParagraphStyle:{name:'一级标题'},contents:'1 主标题',keepWithNext:0});
const child=Object.assign(p(line(10,nextPageFrame)),{appliedParagraphStyle:{name:'二级标题'},contents:'1.1 次标题'});
const body={paragraphs:[primary,child],overflows:false};
assert.equal(repair({recompose(){}},body).length,0);
assert.equal(primary.keepWithNext,0);
assert.equal(repair({recompose(){primary.lines=[line(10,nextPageFrame)];}},body).length,1);
assert.equal(primary.keepWithNext,1);
console.log('PASS heading checks follow actual visual columns, including inside one native frame');
