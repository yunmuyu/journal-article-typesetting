const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const dir=path.resolve(__dirname,'../2-导入_InDesign'),c=vm.createContext({});
for(const name of ['journal_article_assembly.jsxinc','journal_scoped_assembly.jsxinc'])vm.runInContext(fs.readFileSync(path.join(dir,name),'utf8'),c);
const job={data:{blocks:[{role:'body',text:'body'},{role:'figure_caption',text:'图1 image'},{role:'table_gap',text:' '},{role:'body',text:'⟦EQ-001⟧'}]},supplement:{tables:[{rows:[['header'],['value']]}]},structures:{tables:[{widths:[1]}]},tables:[{number:1,kind:'ordinary',headerRows:1}],assets:[{number:1,width:80}],formulas:{entries:[{number:1}]},geometry:{columnWidthMm:85.5}};
assert.equal(c.JournalScopedAssembly.plan(job).formulas,1);
const mixed = {...job,supplement:{tables:[{rows:[['header'],['x ⟦EQ-002⟧']]}]},formulas:{entries:[{number:1},{number:2}]}};
assert.equal(c.JournalScopedAssembly.plan(mixed).formulas,2);
assert.throws(()=>c.JournalScopedAssembly.plan({...mixed,supplement:{tables:[{rows:[['header'],['⟦EQ-001⟧']]}]}}),/SCOPED_FORMULA_DUPLICATE 1/);
assert.throws(()=>c.JournalScopedAssembly.plan({...job,formulas:{entries:[{number:2}]}}),/SCOPED_FORMULA_IDENTITY/);
assert.throws(()=>c.JournalScopedAssembly.plan({...job,assets:[{number:2,width:80}]}),/SCOPED_FIGURE_IDENTITY/);
assert.throws(()=>c.JournalScopedAssembly.plan({...job,tables:[]}),/SCOPED_TABLE_COUNT/);
assert.throws(()=>c.JournalScopedAssembly.plan({...job,assets:[{number:1,width:178}]}),/SCOPED_WIDE_FIGURE_REQUIRES_PLAN/);
const first={role:'body',text:'如图1所示，首次引用。'};
const second={role:'body',text:'如图1所示，再次引用。'};
const caption={role:'figure_caption',text:'图1 示例'};
const place=c.JournalArticleAssembly.placeCaptionsByReference;
assert.equal(place([first,second,caption]).blocks[1],caption);
const placed={...caption,preserveSourcePlacement:true};
assert.equal(place([first,second,placed]).blocks[2],placed);
const tableCaption={role:'table_caption',text:'表1 示例'};
const tableGap={role:'table_gap',text:' '};
const heading={role:'heading2',text:'2.1 小节'};
const tail=[first,tableCaption,tableGap,heading,second,caption];
const defer=c.JournalScopedAssembly.deferTable;
assert.throws(()=>defer(tail,{number:1,paragraphs:2}),/SCOPED_TABLE_DEFERRAL_BOUNDARY/);
assert.deepEqual(tail,[first,tableCaption,tableGap,heading,second,caption]);
assert.equal(defer(tail,{number:1,paragraphs:1}).paragraphs,1);
assert.deepEqual(tail,[first,heading,second,tableCaption,tableGap,caption]);
